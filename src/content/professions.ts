export const professions: Profession[] = rows.map(
  ([id, ru, en, descRu, descEn, family, titles, scenarioIds], index) => ({
    id,
    titleKey: text(`role.${id}`, ru, en),
    descriptionKey: text(`role.${id}.desc`, descRu, descEn),
    family,
    icon: ['⌘', '{ }', '▣', '✓', '⚙', '✳', '◉', '≋', '◇', '⚑'][index % 10],
    scenarioIds,
    startingNode: 'level-0',
    careers: titles.map((title, i) => ({
      id: `level-${i}`,
      titleKey: text(`career.${id}.${i}`, title, title),
      next:
        id === 'frontend' && i === 3
          ? ['level-4', 'level-5']
          : i === titles.length - 1 || (id === 'frontend' && i === 4)
            ? []
            : [`level-${i + 1}`],
      leadership: i >= 3,
      requirements: {
        work: i === 0 ? 0 : Math.max(4, i * 4),
        craft: i * 2 + 1,
        reputation: i * 5,
        communication: i,
        leadership: i >= 4 ? 2 : 0,
        ...(i ? { milestone: 'independent' } : {}),
      },
    })),
  }),
);
export const professionById = Object.fromEntries(professions.map((p) => [p.id, p]));
